const makeVariants = ({ sku, price, discountPrice, stock, size, color, volume, scent }) => {
    const axes = [
        ["size", size],
        ["color", color],
        ["volume", volume],
        ["scent", scent],
    ].filter(([, v]) => v && v.length);

    let combos = [{}];
    for (const [key, values] of axes) {
        combos = combos.flatMap((c) => values.map((v) => ({ ...c, [key]: v })));
    }

    const stocks = distribute(stock, combos.length);
    return combos.map((c, i) => ({
        ...c,
        price,
        discountPrice,
        stock: stocks[i],
        sku: [sku, ...Object.values(c)].join("-").replace(/\s+/g, "").toUpperCase(),
    }));
};

const distribute = (total, n) =>
    Array.from({ length: n }, (_, i) => Math.floor(total / n) + (i < total % n ? 1 : 0));

